/**
 * Extracts markdown image links from a .wh.cpp mod readme code
 */
export function extractScreenshotsFromSource(sourceCode: string): string[] {
  if (!sourceCode) return [];
  const imgRegex = /!\[.*?\]\((https?:\/\/[^\s\)]+)\)/g;
  const imgs: string[] = [];
  let m: RegExpExecArray | null;

  while ((m = imgRegex.exec(sourceCode)) !== null) {
    const url = m[1].trim();
    // Exclude broken imgur links and badges
    if (
      !url.includes("imgur.com") &&
      !url.includes("shields.io") &&
      !url.includes("badge.svg") &&
      (url.endsWith(".png") ||
        url.endsWith(".jpg") ||
        url.endsWith(".jpeg") ||
        url.endsWith(".webp") ||
        url.includes("raw.githubusercontent.com"))
    ) {
      if (!imgs.includes(url)) {
        imgs.push(url);
      }
    }
  }

  return imgs;
}
